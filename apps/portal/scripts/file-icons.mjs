function svg(set, name) {
  const found = set.icons[name] ?? (set.aliases?.[name] && set.icons[set.aliases[name].parent]);
  if (!found) throw new Error(`No icon ${name}`);
  const width = found.width ?? set.width ?? 16, height = found.height ?? set.height ?? 16;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${found.left ?? 0} ${found.top ?? 0} ${width} ${height}">${found.body}</svg>\n`;
}

