// Writes KataTokens.kt from Kata's tokens.css, so the app and the website read
// one palette and one set of measures. Run after changing tokens.css:
//   node apps/compose/scripts/tokens.mjs
// `--check` exits non-zero if the Kotlin file is out of date (for CI).
import { readFileSync, writeFileSync } from "node:fs";

const css = readFileSync(new URL("../../../packages/ui/src/styles/tokens.css", import.meta.url), "utf8");
const start = css.indexOf(":root {");
const root = css.slice(start, css.indexOf("\n}", start));
const raw = Object.fromEntries([...root.matchAll(/--k-([a-z0-9-]+):\s*([^;]+);/g)].map(([, name, value]) => [name, value.trim()]));
const resolve = (value, depth = 0) => {
  const ref = /^var\(--k-([a-z0-9-]+)\)$/.exec(value);
  return ref && depth < 8 ? resolve(raw[ref[1]] ?? value, depth + 1) : value;
};
const camel = (name) => name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const colors = [], sizes = [];
for (const [name, value] of Object.entries(raw)) {
  const v = resolve(value);
  const hex = /^#([0-9a-f]{6})$/i.exec(v);
  if (hex) colors.push(`    val ${camel(name)} = Color(0xFF${hex[1].toUpperCase()})`);
  else if (/^-?\d+(\.\d+)?px$/.test(v) && /^(space|r|control|hairline|rule)/.test(name)) sizes.push(`        val ${camel(name)} = ${parseFloat(v)}.dp`);
}
const out = `// Generated by apps/compose/scripts/tokens.mjs from packages/ui/src/styles/tokens.css. Don't edit.
package app.kimono.theme

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.unit.dp

/** Kata's tokens: the same names the website's CSS uses, without the --k- prefix. */
object Kata {
${colors.join("\n")}

    object Size {
${sizes.join("\n")}
    }
}
`;
const target = new URL("../shared/src/commonMain/kotlin/app/kimono/theme/KataTokens.kt", import.meta.url);
if (process.argv.includes("--check")) {
  const current = readFileSync(target, "utf8");
  if (current !== out) { console.error("KataTokens.kt is out of date: run node apps/compose/scripts/tokens.mjs"); process.exit(1); }
  console.log("KataTokens.kt is up to date");
} else {
  writeFileSync(target, out);
  console.log(`wrote KataTokens.kt: ${colors.length} colours, ${sizes.length} sizes`);
}
