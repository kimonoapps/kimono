// Writes src/theme/tokens.ts from Kata's tokens.css, so the app and the website
// read one palette. Run after changing tokens.css: pnpm --filter @kimono/mobile theme
import { readFileSync, writeFileSync } from "node:fs";

const css = readFileSync(new URL("../../../packages/ui/src/styles/tokens.css", import.meta.url), "utf8");
const root = css.slice(css.indexOf(":root {"), css.indexOf("\n}", css.indexOf(":root {")));
const raw = Object.fromEntries([...root.matchAll(/--k-([a-z0-9-]+):\s*([^;]+);/g)].map(([, name, value]) => [name, value.trim()]));
const resolve = (value, depth = 0) => {
  const ref = /^var\(--k-([a-z0-9-]+)\)$/.exec(value);
  return ref && depth < 8 ? resolve(raw[ref[1]] ?? value, depth + 1) : value;
};
const camel = (name) => name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const colors = {}, sizes = {};
for (const [name, value] of Object.entries(raw)) {
  const v = resolve(value);
  if (/^#[0-9a-f]{3,8}$/i.test(v)) colors[camel(name)] = v;
  else if (/^-?\d+(\.\d+)?px$/.test(v) && /^(space|r|control|hairline|rule)/.test(name)) sizes[camel(name)] = parseFloat(v);
}
const out = `// Generated by scripts/theme.mjs from packages/ui/src/styles/tokens.css. Don't edit.
export const color = ${JSON.stringify(colors, null, 2)} as const;

export const size = ${JSON.stringify(sizes, null, 2)} as const;
`;
writeFileSync(new URL("../src/theme/tokens.ts", import.meta.url), out);
console.log(`wrote src/theme/tokens.ts: ${Object.keys(colors).length} colours, ${Object.keys(sizes).length} sizes`);
